package com.example.fraudcase.api;

import com.example.fraudcase.api.validation.IsoCurrency;
import com.example.fraudcase.api.validation.MaskedIdentifier;
import com.example.fraudcase.api.validation.MaskedMerchantValue;
import com.example.fraudcase.api.validation.NoUnsafeMarkup;
import com.example.fraudcase.domain.CardPossession;
import com.example.fraudcase.domain.IssueType;
import com.example.fraudcase.domain.MerchantRecognition;
import com.example.fraudcase.domain.ReportChannel;
import com.example.fraudcase.domain.TransactionChannel;
import com.example.fraudcase.domain.TransactionStatus;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import jakarta.validation.Valid;
import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PastOrPresent;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.math.BigDecimal;
import java.time.OffsetDateTime;

/**
 * Fraud/dispute case intake contract.
 *
 * <p>Server-managed fields are deliberately absent: {@code caseId} is
 * generated by the application and {@code analystId} will come from the
 * authenticated context once authentication is introduced. Unknown JSON
 * properties are rejected so clients cannot smuggle in fields the server is
 * meant to own.
 *
 * <p>The customer statement is capped at {@value #CUSTOMER_STATEMENT_MAX_LENGTH}
 * characters and treated as untrusted data.
 */
@JsonIgnoreProperties(ignoreUnknown = false)
public record FraudCaseIntakeRequest(

        @NotNull
        @PastOrPresent
        OffsetDateTime reportedAt,

        @NotNull
        ReportChannel channel,

        @NotNull @Valid
        CustomerDetails customer,

        @NotNull @Valid
        TransactionDetails transaction,

        @NotNull @Valid
        ClaimDetails claim,

        @NotNull @Valid
        ConsentDetails consent) {

    public static final int CUSTOMER_STATEMENT_MAX_LENGTH = 2000;

    public record CustomerDetails(

            @NotBlank
            @MaskedIdentifier
            String maskedCustomerRef,

            @NotBlank
            @Size(max = 100)
            @NoUnsafeMarkup
            String homeRegion) {
    }

    public record TransactionDetails(

            // Synthetic reference format: alphabetic prefix, then groups of
            // uppercase letters/digits, e.g. "TXN-2026-784102". The mandatory
            // prefix also prevents raw payment-card numbers from being
            // accepted as references.
            @NotBlank
            @Pattern(regexp = "^[A-Z]{2,8}-[A-Z0-9-]{2,32}$", message = "must be a synthetic reference such as TXN-2026-784102")
            String transactionRef,

            @NotNull
            @Positive
            @Digits(integer = 13, fraction = 2)
            BigDecimal amount,

            @NotBlank
            @IsoCurrency
            String currency,

            @NotNull
            @PastOrPresent
            OffsetDateTime occurredAt,

            @NotNull
            TransactionStatus status,

            @NotNull
            TransactionChannel channel,

            @NotBlank
            @MaskedMerchantValue
            @NoUnsafeMarkup
            String maskedMerchant) {
    }

    public record ClaimDetails(

            @NotNull
            IssueType issueType,

            @NotBlank
            @Size(max = CUSTOMER_STATEMENT_MAX_LENGTH)
            @NoUnsafeMarkup
            String customerStatement,

            @NotNull
            CardPossession cardPossession,

            @NotNull
            MerchantRecognition merchantRecognised) {
    }

    public record ConsentDetails(

            @AssertTrue(message = "must be true: synthetic training data only")
            boolean syntheticDataConfirmed,

            @AssertTrue(message = "must be true: every case requires human review")
            boolean reviewRequired) {
    }
}
